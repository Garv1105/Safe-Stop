import { useMemo, type ReactNode } from 'react'
import { Bar, BarChart, CartesianGrid, Legend, ResponsiveContainer, Tooltip, XAxis, YAxis } from 'recharts'
import { Badge, Spinner } from '../components/ui'
import { useAppData } from '../lib/data'
import { BAND_INFO, BANDS, DR_CAP, GOOD_SCORE, LOW_SCORE } from '../lib/scoring'
import type { AppData } from '../lib/types'
import { SiteHeader } from './SiteHeader'

function sources(d: AppData | undefined) {
  const n = (v: number | undefined) => (v === undefined ? '…' : v.toLocaleString('en-IN'))
  const police = d?.help.features.filter((f) => f.properties.kind.startsWith('Police')).length
  const hosp = d?.help.features.filter((f) => f.properties.kind === 'Hospital').length
  const bus = d?.transit.features.filter((f) => f.properties.kind === 'bus').length
  const metro = d?.transit.features.filter((f) => f.properties.kind === 'metro').length
  return [
    { what: 'Street lamps', count: n(d?.lamps.features.length), source: 'OpenStreetMap (highway=street_lamp)', real: true },
    { what: 'Road lighting tags & road type', count: 'all walkable roads', source: 'OpenStreetMap (lit=*, highway=*)', real: true },
    { what: 'Shops, food, pharmacies, ATMs, fuel', count: n(d?.places.features.length), source: 'OpenStreetMap; opening_hours if tagged, else default hours per category', real: true },
    { what: 'Bus stops / metro stations', count: `${n(bus)} / ${n(metro)}`, source: 'OpenStreetMap', real: true },
    { what: 'Police stations & outposts', count: n(police), source: 'OpenCity: Bengaluru Urban police station & outpost locations (KML)', real: true },
    { what: 'Hospitals', count: n(hosp), source: 'OpenStreetMap (amenity=hospital)', real: true },
    { what: 'Walking routes', count: `${d?.routes.pairs.length ?? '…'} demo trips`, source: 'Shortest: OSRM foot profile (FOSSGIS server). Safest / balanced: safety-weighted shortest path on the OSM road network', real: true },
    { what: 'Community reports', count: n(d?.reports.reports.length), source: 'Generated by script (seed 42), loosely linked to lighting and activity', real: false },
  ]
}

export default function About() {
  const { data, error } = useAppData()

  const histogram = useMemo(() => {
    if (!data) return []
    const buckets = Array.from({ length: 10 }, (_, i) => ({ range: `${i * 10}–${i * 10 + 9}`, evening: 0, late: 0, night: 0 }))
    for (const c of data.cells) for (const b of BANDS) buckets[Math.min(9, Math.floor(c.score[b] / 10))][b]++
    return buckets
  }, [data])

  return (
    <div className="min-h-full bg-white dark:bg-zinc-950">
      <SiteHeader />
      <main className="mx-auto max-w-4xl px-6 py-12">
        <h1 className="text-3xl font-semibold tracking-tight">About the data</h1>
        <p className="mt-3 max-w-2xl text-zinc-600 dark:text-zinc-400">
          This is a presentation prototype covering about 3 km around Dayananda Sagar College of Engineering. All data is precomputed into static files. There is no server and nothing you do here is sent anywhere.
        </p>

        <Section title="Data sources">
          <div className="overflow-x-auto rounded-xl border border-zinc-200 dark:border-zinc-800">
            <table className="w-full text-left text-sm">
              <thead className="bg-zinc-50 text-[12px] text-zinc-500 dark:bg-zinc-900 dark:text-zinc-400">
                <tr>
                  <th className="px-4 py-3 font-medium">Data</th>
                  <th className="px-4 py-3 font-medium">Count</th>
                  <th className="px-4 py-3 font-medium">Source</th>
                  <th className="px-4 py-3 font-medium">Type</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-zinc-100 dark:divide-zinc-800">
                {sources(data).map((s) => (
                  <tr key={s.what}>
                    <td className="px-4 py-3 font-medium">{s.what}</td>
                    <td className="px-4 py-3 tabular-nums">{s.count}</td>
                    <td className="px-4 py-3 text-zinc-600 dark:text-zinc-400">{s.source}</td>
                    <td className="px-4 py-3">{s.real ? <Badge tone="real">Real</Badge> : <Badge tone="synthetic">Synthetic</Badge>}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
          <p className="mt-3 text-[13px] text-zinc-500">
            Map tiles: OpenFreeMap · Map data © OpenStreetMap contributors (ODbL). OpenStreetMap coverage is uneven: few street lamps are mapped here, so main-road share is used as a lighting hint. A missing
            lighting tag counts as unknown, not dark.
          </p>
        </Section>

        <Section title="How a score is calculated">
          <div className="rounded-xl bg-zinc-950 p-5 font-mono text-[14px] text-zinc-100">
            S = 100 × (0.35·L + 0.25·A<sub>t</sub> + 0.15·T + 0.25·H) + ΔR
          </div>
          <dl className="mt-4 grid gap-3 text-sm sm:grid-cols-2">
            <Term k="L · Lighting">Street lamps in and around the block, share of main roads, and lit=yes/no tags where mapped.</Term>
            <Term k="A · Activity">Places likely open in the time band, using opening hours or a default per category (e.g. shops till 9:30 pm, restaurants till 11 pm, fuel 24 h).</Term>
            <Term k="T · Transit">Bus stops and metro stations in the block and its neighbours.</Term>
            <Term k="H · Help">Straight-line distance to the nearest police station or outpost, and hospital.</Term>
            <Term k="ΔR · Reports">Community reports for that time band, capped at ±{DR_CAP} points. In this prototype they are simulated.</Term>
            <Term k="Blocks">H3 hexagons (resolution 9, about 0.1 km² each). Parts are scaled 0–1 within the pilot area.</Term>
          </dl>
          <p className="mt-4 text-sm text-zinc-600 dark:text-zinc-400">
            Labels: {GOOD_SCORE}+ Good · {LOW_SCORE}–{GOOD_SCORE - 1} Moderate · under {LOW_SCORE} Low lighting &amp; activity. Time bands:{' '}
            {BANDS.map((b) => `${BAND_INFO[b].label} ${BAND_INFO[b].hours}`).join(' · ')}.
          </p>
        </Section>

        <Section title="Score spread across the pilot area">
          {error ? (
            <p className="text-sm text-zinc-500">Chart unavailable: {error}</p>
          ) : !data ? (
            <Spinner label="Loading scores…" />
          ) : (
            <div className="h-72">
              <ResponsiveContainer width="100%" height="100%">
                <BarChart data={histogram} margin={{ left: -16, right: 8 }}>
                  <CartesianGrid vertical={false} stroke="#e4e4e7" strokeOpacity={0.5} />
                  <XAxis dataKey="range" tick={{ fontSize: 12, fill: '#71717a' }} tickLine={false} axisLine={false} />
                  <YAxis tick={{ fontSize: 12, fill: '#71717a' }} tickLine={false} axisLine={false} allowDecimals={false} />
                  <Tooltip cursor={{ fill: 'rgba(99,102,241,0.08)' }} contentStyle={{ borderRadius: 8, fontSize: 12 }} />
                  <Legend wrapperStyle={{ fontSize: 12 }} />
                  <Bar dataKey="evening" name="Evening" fill="#a5b4fc" radius={[3, 3, 0, 0]} />
                  <Bar dataKey="late" name="Late" fill="#6366f1" radius={[3, 3, 0, 0]} />
                  <Bar dataKey="night" name="Night" fill="#312e81" radius={[3, 3, 0, 0]} />
                </BarChart>
              </ResponsiveContainer>
            </div>
          )}
          <p className="mt-2 text-[13px] text-zinc-500">Number of blocks in each score range. Scores drop later at night as shops close.</p>
        </Section>

        <Section title="Privacy principles">
          <ul className="grid gap-3 text-sm sm:grid-cols-2">
            <Principle t="No accounts">Scores and routes work without signing in.</Principle>
            <Principle t="Anonymous reports">Reports carry a block, a category and a time band. No names, no free text, no exact location.</Principle>
            <Principle t="Describe, don't label">We say what is missing (lighting, open places, help nearby). We never call an area dangerous.</Principle>
            <Principle t="Sharing is opt-in">Trip sharing only starts when you press start, and ends when you arrive or stop it.</Principle>
          </ul>
        </Section>

        <Section title="Roadmap to the full product">
          <ol className="space-y-2 text-sm text-zinc-700 dark:text-zinc-300">
            {[
              'Python data pipeline refreshing OSM, police and transit data on a schedule',
              'PostGIS + FastAPI backend with live safety-weighted routing for any start and end point',
              'Real anonymous reports with rate limits and moderation',
              'Field checks of lighting with volunteer walks to validate scores',
              'Real trip sharing with SMS fallback, then more Bengaluru neighbourhoods',
            ].map((s, i) => (
              <li key={s} className="flex gap-3">
                <span className="grid h-6 w-6 shrink-0 place-items-center rounded-full bg-brand-50 text-[12px] font-semibold text-brand-700 dark:bg-brand-500/10 dark:text-brand-100">{i + 1}</span>
                {s}
              </li>
            ))}
          </ol>
        </Section>
      </main>
    </div>
  )
}

function Section({ title, children }: { title: string; children: ReactNode }) {
  return (
    <section className="mt-12">
      <h2 className="mb-4 text-xl font-semibold tracking-tight">{title}</h2>
      {children}
    </section>
  )
}

function Term({ k, children }: { k: string; children: ReactNode }) {
  return (
    <div className="rounded-lg border border-zinc-200 p-3 dark:border-zinc-800">
      <dt className="font-semibold">{k}</dt>
      <dd className="mt-1 text-zinc-600 dark:text-zinc-400">{children}</dd>
    </div>
  )
}

function Principle({ t, children }: { t: string; children: ReactNode }) {
  return (
    <li className="rounded-lg bg-zinc-50 p-4 dark:bg-zinc-900">
      <p className="font-semibold">{t}</p>
      <p className="mt-1 text-zinc-600 dark:text-zinc-400">{children}</p>
    </li>
  )
}
